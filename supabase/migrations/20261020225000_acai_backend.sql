-- 1. Tabela de Configurações do Açaí e Sorvete
create table if not exists public.acai_settings (
    id integer primary key default 1 check (id = 1),
    price_per_kg numeric(10, 2) not null default 60.00,
    ice_cream_price_per_kg numeric(10, 2) not null default 50.00,
    acai_image text not null default '',
    ice_cream_image text not null default '',
    min_grams integer not null default 300,
    step_grams integer not null default 50,
    weight_options jsonb not null default '[300, 400, 500, 750, 1000]'::jsonb,
    whatsapp_number text not null default '',
    is_open boolean not null default true,
    updated_at timestamptz not null default now()
);

alter table public.acai_settings
    add column if not exists ice_cream_price_per_kg numeric(10, 2) not null default 50.00;
alter table public.acai_settings
    add column if not exists acai_image text not null default '';
alter table public.acai_settings
    add column if not exists ice_cream_image text not null default '';

insert into public.acai_settings (id, price_per_kg, ice_cream_price_per_kg, min_grams, step_grams, weight_options, whatsapp_number, is_open)
values (1, 60.00, 50.00, 300, 50, '[300, 400, 500, 750, 1000]'::jsonb, '', true)
on conflict (id) do nothing;

alter table public.acai_settings enable row level security;

drop policy if exists "acai_settings_select_all" on public.acai_settings;
create policy "acai_settings_select_all"
    on public.acai_settings for select
    to anon, authenticated
    using (true);

drop policy if exists "acai_settings_write_all" on public.acai_settings;
create policy "acai_settings_write_all"
    on public.acai_settings for all
    to anon, authenticated
    using (true)
    with check (true);

grant select, insert, update on public.acai_settings to anon, authenticated;

