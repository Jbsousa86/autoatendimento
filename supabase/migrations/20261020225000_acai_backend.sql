-- 5. Tabela de Pedidos de Açaí e Sorvete (Isolada da tabela orders)
create table if not exists public.acai_orders (
    id uuid primary key default gen_random_uuid(),
    order_number text not null,
    customer_name text not null default 'Cliente',
    customer_phone text,
    customer_address text,
    delivery_type text not null default 'entrega' check (delivery_type in ('entrega', 'retirada', 'balcao')),
    cashier_name text,
    payment_method text,
    change_amount numeric(10, 2),
    observation text,
    grams integer not null default 0,
    price_per_kg numeric(10, 2) not null default 60.00,
    addons jsonb not null default '[]'::jsonb,
    items jsonb not null default '[]'::jsonb,
    total numeric(10, 2) not null default 0.00,
    status text not null default 'pending' check (status in ('pending', 'preparing', 'ready', 'finished', 'cancelled')),
    created_at timestamptz not null default now()
);

alter table public.acai_orders add column if not exists cashier_name text;

do $$
begin
    alter table public.acai_orders drop constraint if exists acai_orders_delivery_type_check;
    alter table public.acai_orders add constraint acai_orders_delivery_type_check
        check (delivery_type in ('entrega', 'retirada', 'balcao'));
exception when others then
    null;
end;
$$;

create index if not exists idx_acai_orders_created_at
    on public.acai_orders (created_at desc);

create index if not exists idx_acai_orders_status
    on public.acai_orders (status, created_at desc);

alter table public.acai_orders enable row level security;

drop policy if exists "acai_orders_select_all" on public.acai_orders;
create policy "acai_orders_select_all"
